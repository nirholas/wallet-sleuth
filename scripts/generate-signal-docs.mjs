#!/usr/bin/env node
/**
 * Regenerates docs/signals.md from the engine's signal registry.
 *
 * The prose lives on each Signal object next to the code that implements it, so the documentation
 * and the behaviour are edited in the same place and cannot drift. Run after changing any signal:
 *
 *   npm run docs:signals
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALL_SIGNALS } from '../packages/core/dist/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const CATEGORY_ORDER = ['control', 'funding', 'flow', 'coactivity', 'behavioral'];
const CATEGORY_INTRO = {
  control: 'Evidence that one key can act for both addresses. This is the strongest class Braid has, because it reads state and signatures rather than inferring intent from behaviour.',
  funding: 'Evidence about where an address got its money, and especially where it got its first money. An account cannot transact before someone funds it, which makes the funder unusually informative.',
  flow: 'Evidence from value moving between the addresses, or from both addresses moving value into the same place.',
  coactivity: 'Evidence from the company an address keeps, once the places everybody visits have been removed.',
  behavioral: 'Evidence from habits. Suggestive on its own, genuinely useful as corroboration, never sufficient alone.',
};

const lines = [
  '# Signals',
  '',
  '<!-- Generated by scripts/generate-signal-docs.mjs from the signal registry. Edit the descriptions in packages/core/src/signals and rerun `npm run docs:signals`. -->',
  '',
  `Braid runs ${ALL_SIGNALS.length} signals. Each one produces evidence with a strength between 0 and 1; the`,
  "signal's weight is what that evidence is worth at full strength. Weights are deliberately not equal:",
  'reading an ownership record off chain state is not the same kind of claim as noticing two wallets are',
  'awake at the same time of day, and the scoring should not pretend otherwise.',
  '',
  'See [scoring](./scoring.md) for how these combine, and [interpreting results](./interpreting-results.md)',
  'for what the resulting number licenses you to say.',
  '',
  '## Weights at a glance',
  '',
  '| Signal | Category | Weight | Chains |',
  '| --- | --- | --- | --- |',
  ...[...ALL_SIGNALS]
    .sort((a, b) => b.weight - a.weight)
    .map(
      (signal) =>
        `| \`${signal.id}\` | ${signal.category} | ${signal.weight.toFixed(2)} | ${(signal.namespaces ?? ['evm', 'solana']).join(', ')} |`,
    ),
  '',
];

for (const category of CATEGORY_ORDER) {
  const group = ALL_SIGNALS.filter((signal) => signal.category === category).sort((a, b) => b.weight - a.weight);
  if (group.length === 0) continue;
  lines.push(`## ${category[0].toUpperCase()}${category.slice(1)}`, '', CATEGORY_INTRO[category], '');
  for (const signal of group) {
    lines.push(
      `### ${signal.title}`,
      '',
      `\`${signal.id}\` · weight ${signal.weight.toFixed(2)} · ${(signal.namespaces ?? ['evm', 'solana']).join(' and ')}`,
      '',
      signal.description,
      '',
    );
  }
}

lines.push(
  '## Choosing which signals run',
  '',
  'Every signal runs by default. To restrict an analysis, pass the ids you want:',
  '',
  '```bash',
  'curl -s localhost:8787/v1/analyze -H "content-type: application/json" -d \'{',
  '  "addresses": ["0x...", "0x..."],',
  '  "options": { "signals": ["direct-transfer", "common-first-funder"] }',
  '}\'',
  '```',
  '',
  'The live catalogue, including weights, is served at `GET /v1/signals`.',
  '',
);

writeFileSync(join(root, 'docs/signals.md'), lines.join('\n'));
console.log(`wrote docs/signals.md (${ALL_SIGNALS.length} signals)`);
