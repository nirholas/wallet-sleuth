#!/usr/bin/env node
/**
 * Regenerates THIRD-PARTY-NOTICES.md from the installed runtime dependency tree.
 *
 * Wallet Sleuth itself is proprietary, but it ships on top of open source packages whose licences
 * require their notices to travel with any distribution. This produces that attribution from what is
 * actually installed rather than from a hand maintained list, so it cannot silently go stale.
 *
 *   npm run notices
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const workspaces = new Set(['@wallet-sleuth/core', '@wallet-sleuth/api', '@wallet-sleuth/cli', '@wallet-sleuth/web']);

const paths = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], { cwd: root, encoding: 'utf8' })
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean);

const packages = new Map();
for (const path of paths) {
  const marker = path.lastIndexOf('/node_modules/');
  if (marker < 0) continue;
  const name = path.slice(marker + '/node_modules/'.length);
  if (workspaces.has(name) || packages.has(name)) continue;
  const manifestPath = join(path, 'package.json');
  if (!existsSync(manifestPath)) continue;
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const license =
    manifest.license ??
    (Array.isArray(manifest.licenses) ? manifest.licenses.map((entry) => entry.type).join(' OR ') : undefined) ??
    'see package';
  packages.set(name, {
    version: manifest.version ?? '',
    license,
    homepage: manifest.homepage ?? (typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url) ?? '',
  });
}

const sorted = [...packages.entries()].sort(([a], [b]) => a.localeCompare(b));
const byLicense = new Map();
for (const [, meta] of sorted) byLicense.set(meta.license, (byLicense.get(meta.license) ?? 0) + 1);

const lines = [
  '# Third party notices',
  '',
  '<!-- Generated by scripts/generate-third-party-notices.mjs. Run `npm run notices` after changing dependencies. -->',
  '',
  'Wallet Sleuth is proprietary software; see [LICENSE](LICENSE). It is built on the open source',
  'packages listed below, each of which remains governed by its own licence. Those licences are',
  'reproduced in full in each package under `node_modules/`.',
  '',
  `${sorted.length} runtime packages, by licence:`,
  '',
  ...[...byLicense.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([license, count]) => `- ${license}: ${count}`),
  '',
  '| Package | Version | Licence |',
  '| --- | --- | --- |',
  ...sorted.map(([name, meta]) => {
    const label = meta.homepage ? `[${name}](${meta.homepage.replace(/^git\+/, '').replace(/\.git$/, '')})` : name;
    return `| ${label} | ${meta.version} | ${meta.license} |`;
  }),
  '',
];

writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), lines.join('\n'));
console.log(`wrote THIRD-PARTY-NOTICES.md (${sorted.length} packages)`);
